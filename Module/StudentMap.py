def schedule(start, pickup, deliveries, goal):
    """决定送货的**顺序**。

    无人机飞在楼之上（巡航高度高于所有楼），所以**两点之间直线可达** ——
    怎么走不成问题，问题只剩「**按什么顺序送**」。

    输入变量：
        start:       起点格子 (i, j)
        pickup:      取货点格子 (i, j) —— 必须先到这里取货
        deliveries:  送货点列表 [(i, j), ...]（顺序是文件里写的原始顺序）
        goal:        终点格子 (i, j) —— 送完最后要到这里
    返回：
        一个 **下标列表**，表示按什么顺序访问 deliveries。
        例如 [2, 0, 1] 表示先送第 3 个、再第 1 个、最后第 2 个。
        **必须是 0..len(deliveries)-1 的一个排列**，长度、元素都要对。

    目标：让总路程（取货点 -> 各送货点 -> 终点，全部走直线）尽量短。

    当前这几个点：**照文件里写的顺序送要 127.8 m，最短只要 102.2 m** —— 差 25 米。

    下面是"按原顺序送"的默认实现 —— 它一定对，但明显不是最短的。
    试试看怎么改进：
      * [暴力枚举] 送货点只有 3 个，所有排列一共才 6 种，全试一遍取最短的。
                    保证最优，但点一多（比如 10 个 = 362 万种）就跑不动了。
                    这叫旅行商问题（TSP）。
      * [最近邻]   每次挑"离当前位置最近"的那个还没送的点。
                    简单、快，但不保证最优。
      * [2-opt]    先用最近邻得到一个顺序，再反复尝试交换其中两个点，
                    只要总路程变短就保留。能从局部最优里跳出来。

    小提示：每条航线是直线，所以距离就是欧氏距离：
        math.hypot(b[0] - a[0], b[1] - a[1])
    """
    return list(range(len(deliveries)))          # 默认：就按文件里的顺序送
